export function getWordOfTheDay(languageCode) {
  const lessons = LESSONS_DATA[languageCode] || LESSONS_DATA.Spanish;
  const today = new Date().toISOString().slice(0, 10);
  const seed = `${today}-${languageCode}`;
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return lessons[hash % lessons.length];
}
